export type PerfektCategory =
  | 'regular'
  | 'irregular'
  | 'mixed'
  | 'ieren'
  | 'separable'
  | 'inseparable'
  | 'sein'

export const CATEGORY_LABEL: Record<PerfektCategory, string> = {
  regular:     'Regular',
  irregular:   'Irregular',
  mixed:       'Misto',
  ieren:       '-ieren',
  separable:   'Separável',
  inseparable: 'Inseparável',
  sein:        'sein',
}

export const CATEGORY_TIP: Record<PerfektCategory, string> = {
  regular:     'ge- + radical + -t',
  irregular:   'ge- + radical alterado + -en',
  mixed:       'ge- + radical alternado + -t (mudança vocálica)',
  ieren:       'verbos em -ieren não recebem ge-',
  separable:   'prefixo + ge- + radical + -t/-en',
  inseparable: 'prefixos be-/ver-/er-/ge-/ent-/... → sem ge-',
  sein:        'movimento ou mudança de estado → sein',
}

